"""
LLM-Compiled Rules: Implementation C.
An LLM converts the statutory rule text into executable rules once.
You review them, and they then run without an LLM.

Architecture:
1. Compiler: Reads official rule text and compiles it into an executable rules specification / Python AST.
2. Review & Verification Gate: Tests the compiled rules against statutory invariants.
3. Runtime Execution: Runs purely deterministic compiled rules at runtime (Zero LLM calls, Zero latency, Zero dollar cost).
"""

import time
from typing import Dict, Any, Tuple, List
from project_a.tax_models import TaxpayerInput, TaxBreakdown, TaxRegime, FinancialYear, AuditStep
from project_a.rule_text import RULE_TEXT_FY2425, RULE_TEXT_FY2526


class CompiledRulesFY2425:
    """
    Code generated by LLM Compiler from RULE_TEXT_FY2425 and reviewed by tax engineer.
    Zero external dependencies, purely deterministic.
    """
    @staticmethod
    def calculate_old(taxpayer: TaxpayerInput) -> TaxBreakdown:
        steps: List[AuditStep] = []
        gross = taxpayer.gross_salary
        
        # 1. Standard Deduction (Sec 16(ia))
        std_ded = min(gross, 50000.0)
        steps.append(AuditStep("Standard Deduction", "Sec 16(ia)", std_ded, gross - std_ded, "₹50,000 standard deduction"))
        
        # 2. HRA Exemption (Sec 10(13A))
        hra_exempt = 0.0
        if taxpayer.hra_received > 0 and taxpayer.rent_paid > 0:
            excess_rent = max(0.0, taxpayer.rent_paid - 0.10 * taxpayer.basic_salary)
            pct_salary = (0.50 if taxpayer.is_metro else 0.40) * taxpayer.basic_salary
            hra_exempt = min(taxpayer.hra_received, excess_rent, pct_salary)
        steps.append(AuditStep("HRA Exemption", "Sec 10(13A)", hra_exempt, gross - std_ded - hra_exempt, f"HRA exempt: ₹{hra_exempt:,.2f}"))
        
        # Sec 24(b) Home loan interest
        hp_loss = min(taxpayer.home_loan_interest, 200000.0)
        
        # Chapter VI-A
        c_80c = min(taxpayer.sec_80c, 150000.0)
        c_80ccd = min(taxpayer.sec_80ccd_1b, 50000.0)
        c_80d_self = min(taxpayer.sec_80d_self, 50000.0 if taxpayer.age >= 60 else 25000.0)
        c_80d_par = min(taxpayer.sec_80d_parents, 50000.0 if taxpayer.parents_senior else 25000.0)
        tot_via = c_80c + c_80ccd + c_80d_self + c_80d_par
        
        # Net taxable income
        gti = max(0.0, gross - std_ded - hra_exempt - taxpayer.professional_tax - taxpayer.other_exemptions - hp_loss)
        tot_via = min(tot_via, gti)
        taxable_income = round(max(0.0, gti - tot_via) / 10.0) * 10.0
        
        # Slabs
        if taxable_income <= 250000:
            base_tax = 0.0
        elif taxable_income <= 500000:
            base_tax = (taxable_income - 250000) * 0.05
        elif taxable_income <= 1000000:
            base_tax = 12500.0 + (taxable_income - 500000) * 0.20
        else:
            base_tax = 112500.0 + (taxable_income - 1000000) * 0.30
        steps.append(AuditStep("Base Tax Calculation", "Old Slabs", base_tax, base_tax, f"Base tax: ₹{base_tax:,.2f}"))
        
        # Rebate 87A
        rebate_87a = min(base_tax, 12500.0) if taxable_income <= 500000 else 0.0
        tax_after_rebate = base_tax - rebate_87a
        
        # Surcharge with marginal relief
        surcharge = 0.0
        relief = 0.0
        if tax_after_rebate > 0:
            if taxable_income > 50000000:
                nom = tax_after_rebate * 0.37
                max_p = 112500 + 49000000*0.30 + (112500 + 49000000*0.30)*0.25 + (taxable_income - 50000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 20000000:
                nom = tax_after_rebate * 0.25
                max_p = 112500 + 19000000*0.30 + (112500 + 19000000*0.30)*0.15 + (taxable_income - 20000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 10000000:
                nom = tax_after_rebate * 0.15
                max_p = 112500 + 9000000*0.30 + (112500 + 9000000*0.30)*0.10 + (taxable_income - 10000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 5000000:
                nom = tax_after_rebate * 0.10
                max_p = 112500 + 4000000*0.30 + (taxable_income - 5000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
                
        cess = (tax_after_rebate + surcharge) * 0.04
        total_payable = int(round((tax_after_rebate + surcharge + cess) / 10.0) * 10)
        
        return TaxBreakdown(
            regime=TaxRegime.OLD,
            financial_year=FinancialYear.FY2024_25,
            gross_salary=gross,
            standard_deduction=std_ded,
            hra_exemption=hra_exempt,
            sec_24b_loss=hp_loss,
            chapter_vi_a=tot_via,
            total_deductions=std_ded + hra_exempt + hp_loss + tot_via,
            taxable_income=taxable_income,
            base_tax=base_tax,
            rebate_87a=rebate_87a,
            tax_after_rebate=tax_after_rebate,
            surcharge=surcharge,
            marginal_relief_surcharge=relief,
            cess=cess,
            total_tax_payable=total_payable,
            audit_trail=steps
        )

    @staticmethod
    def calculate_new(taxpayer: TaxpayerInput) -> TaxBreakdown:
        steps: List[AuditStep] = []
        gross = taxpayer.gross_salary
        
        # Standard deduction: ₹75,000 (FY 2024-25 Finance (No. 2) Act 2024)
        std_ded = min(gross, 75000.0)
        taxable_income = round(max(0.0, gross - std_ded) / 10.0) * 10.0
        
        # New slabs FY 2024-25
        if taxable_income <= 300000:
            base_tax = 0.0
        elif taxable_income <= 700000:
            base_tax = (taxable_income - 300000) * 0.05
        elif taxable_income <= 1000000:
            base_tax = 20000.0 + (taxable_income - 700000) * 0.10
        elif taxable_income <= 1200000:
            base_tax = 50000.0 + (taxable_income - 1000000) * 0.15
        elif taxable_income <= 1500000:
            base_tax = 80000.0 + (taxable_income - 1200000) * 0.20
        else:
            base_tax = 140000.0 + (taxable_income - 1500000) * 0.30
            
        # Rebate 87A + Marginal Relief
        if taxable_income <= 700000:
            rebate_87a = base_tax
        else:
            excess = taxable_income - 700000.0
            rebate_87a = max(0.0, base_tax - excess) if base_tax > excess else 0.0
            
        tax_after_rebate = base_tax - rebate_87a
        
        # Surcharge (capped at 25%)
        surcharge = 0.0
        relief = 0.0
        if tax_after_rebate > 0:
            if taxable_income > 20000000:
                nom = tax_after_rebate * 0.25
                max_p = 140000 + 18500000*0.30 + (140000 + 18500000*0.30)*0.15 + (taxable_income - 20000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 10000000:
                nom = tax_after_rebate * 0.15
                max_p = 140000 + 8500000*0.30 + (140000 + 8500000*0.30)*0.10 + (taxable_income - 10000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 5000000:
                nom = tax_after_rebate * 0.10
                max_p = 140000 + 3500000*0.30 + (taxable_income - 5000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
                
        cess = (tax_after_rebate + surcharge) * 0.04
        total_payable = int(round((tax_after_rebate + surcharge + cess) / 10.0) * 10)
        
        return TaxBreakdown(
            regime=TaxRegime.NEW,
            financial_year=FinancialYear.FY2024_25,
            gross_salary=gross,
            standard_deduction=std_ded,
            hra_exemption=0.0,
            sec_24b_loss=0.0,
            chapter_vi_a=0.0,
            total_deductions=std_ded,
            taxable_income=taxable_income,
            base_tax=base_tax,
            rebate_87a=rebate_87a,
            tax_after_rebate=tax_after_rebate,
            surcharge=surcharge,
            marginal_relief_surcharge=relief,
            cess=cess,
            total_tax_payable=total_payable,
            audit_trail=steps
        )


class CompiledRulesFY2526:
    """
    Code generated by LLM Compiler from RULE_TEXT_FY2526 and reviewed by tax engineer.
    Includes Budget 2025 revised slabs and ₹12,00,000 Section 87A rebate limit.
    """
    @staticmethod
    def calculate_old(taxpayer: TaxpayerInput) -> TaxBreakdown:
        return CompiledRulesFY2425.calculate_old(taxpayer)

    @staticmethod
    def calculate_new(taxpayer: TaxpayerInput) -> TaxBreakdown:
        steps: List[AuditStep] = []
        gross = taxpayer.gross_salary
        
        std_ded = min(gross, 75000.0)
        taxable_income = round(max(0.0, gross - std_ded) / 10.0) * 10.0
        
        # FY 2025-26 Slabs:
        # 0-4L: Nil, 4-8L: 5%, 8-12L: 10%, 12-16L: 15%, 16-20L: 20%, 20-24L: 25%, >24L: 30%
        if taxable_income <= 400000:
            base_tax = 0.0
        elif taxable_income <= 800000:
            base_tax = (taxable_income - 400000) * 0.05
        elif taxable_income <= 1200000:
            base_tax = 20000.0 + (taxable_income - 800000) * 0.10
        elif taxable_income <= 1600000:
            base_tax = 60000.0 + (taxable_income - 1200000) * 0.15
        elif taxable_income <= 2000000:
            base_tax = 120000.0 + (taxable_income - 1600000) * 0.20
        elif taxable_income <= 2400000:
            base_tax = 200000.0 + (taxable_income - 2000000) * 0.25
        else:
            base_tax = 300000.0 + (taxable_income - 2400000) * 0.30
            
        # Sec 87A Rebate for FY 2025-26: Threshold is ₹12,00,000!
        if taxable_income <= 1200000:
            rebate_87a = base_tax
        else:
            excess = taxable_income - 1200000.0
            rebate_87a = max(0.0, base_tax - excess) if base_tax > excess else 0.0
            
        tax_after_rebate = base_tax - rebate_87a
        
        # Surcharge (capped at 25%)
        surcharge = 0.0
        relief = 0.0
        if tax_after_rebate > 0:
            if taxable_income > 20000000:
                nom = tax_after_rebate * 0.25
                max_p = 300000 + 17600000*0.25 + (300000 + 17600000*0.25)*0.15 + (taxable_income - 20000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 10000000:
                nom = tax_after_rebate * 0.15
                max_p = 60000 + 8800000*0.15 + (60000 + 8800000*0.15)*0.10 + (taxable_income - 10000000)
                surcharge = max(0.0, max_p - tax_after_rebate) if (tax_after_rebate + nom) > max_p else nom
                relief = nom - surcharge
            elif taxable_income > 5000000:
                nom = tax_after_rebate * 0.10
                max_p = 60000 + 3800000*0.15 + (taxable_income - 5000000)
